#!/usr/bin/env bash
# Regenerates the third-party license notices shipped with sqlsift:
#
#   THIRD-PARTY-LICENSES.md                 crates compiled into the binaries, the npm
#                                           package and the playground (cargo-about)
#   editors/vscode/THIRD-PARTY-NOTICES.md   npm packages bundled into the VS Code
#                                           extension (production dependencies)
#
# Run it after changing dependencies. CI ("Licenses") fails when either file is stale.
# Needs cargo-about and the extension's node_modules (`npm ci` in editors/vscode).

set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

cargo about generate --workspace --locked --offline --fail about.hbs -o THIRD-PARTY-LICENSES.md
# sqlsift's own crates are not third-party, and their version would make the file
# stale on every release (the release PR bumps it)
sed -i.bak -E '/^- \[sqlsift-[a-z]+ [^]]*\]\(https:\/\/github\.com\/yukikotani231\/sqlsift\)$/d' THIRD-PARTY-LICENSES.md
rm THIRD-PARTY-LICENSES.md.bak

node - <<'JS'
const fs = require("fs");
const path = require("path");

const dir = "editors/vscode";
const lock = JSON.parse(fs.readFileSync(path.join(dir, "package-lock.json"), "utf8"));
const out = [
  "# Third-party notices",
  "",
  "The sqlsift VS Code extension bundles the following npm packages. The bundled",
  "sqlsift-lsp binary includes the crates listed in THIRD-PARTY-LICENSES.md.",
  "This file is generated by scripts/third-party-licenses.sh; do not edit it by hand.",
];
const entries = Object.entries(lock.packages)
  .filter(([key, pkg]) => key !== "" && !pkg.dev)
  .sort(([a], [b]) => a.localeCompare(b));
for (const [key, pkg] of entries) {
  const pkgDir = path.join(dir, key);
  const name = key.slice(key.lastIndexOf("node_modules/") + "node_modules/".length);
  const files = fs.readdirSync(pkgDir).filter((f) => /(licen[cs]e|notice)/i.test(f)).sort();
  if (files.length === 0) throw new Error(`no license file in ${pkgDir}`);
  out.push("", `## ${name} ${pkg.version} (${pkg.license})`);
  for (const file of files) {
    const text = fs.readFileSync(path.join(pkgDir, file), "utf8").replace(/\r\n/g, "\n").trim();
    out.push("", "```text", text, "```");
  }
}
fs.writeFileSync(path.join(dir, "THIRD-PARTY-NOTICES.md"), out.join("\n") + "\n");
JS
